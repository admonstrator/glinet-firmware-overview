def entry_link(entry):
    if entry.get('download'):
        return entry['download'][0].get('link', '') or ''
    return ''

def api_stage_name(stage):
    """Map an internal stage key to its lowercase API path segment (BETA_OPEN24 -> beta-open24)."""
    return stage.lower().replace('_open', '-open')


def stage_label(stage, entry=None):
    """Human readable plain-text stage label, e.g. 'BETA (OP24)' for open variants."""
    if stage.startswith('BETA_OPEN'):
        base = (entry or {}).get('_openwrt_base') or stage[len('BETA_OPEN'):] or '24'
        return f'BETA (OP{base})'
    return stage

def ordered_stages(model_stages):
    """Order a model's stage keys for display: known stages first, unknown ones
    alphabetically, and OpenWrt open variants directly after BETA (they are
    rendered in the BETA column of the overview as well)."""
    regular = [s for s in model_stages if not s.startswith('BETA_OPEN')]
    open_variants = sorted(s for s in model_stages if s.startswith('BETA_OPEN'))
    ordered = [s for s in STAGE_ORDER if s in regular] + sorted(s for s in regular if s not in STAGE_ORDER)
    insert_at = ordered.index('BETA') + 1 if 'BETA' in ordered else len(ordered)
    return ordered[:insert_at] + open_variants + ordered[insert_at:]


def group_models_by_type(models, models_metadata):
    """Model codes grouped by device type (ROUTER/IOT/KVM), sorted by display name."""
    grouped = {'ROUTER': [], 'IOT': [], 'KVM': []}
    for code in models:
        m_type = models_metadata.get(code, {}).get('type', 'ROUTER')
        grouped.setdefault(m_type, []).append(code)
    for codes in grouped.values():
        codes.sort(key=lambda c: models_metadata.get(c, {}).get('name', c))
    return grouped

def overview_stage_columns(models):
    """Stage columns of the overview: known stages first, the rest alphabetically,
    OpenWrt open variants excluded (they are shown inside the BETA column)."""
    all_stages = set()
    for stages in models.values():
        all_stages.update(s for s in stages if not s.startswith('BETA_OPEN'))
    return [s for s in STAGE_ORDER if s in all_stages] + [s for s in sorted(all_stages) if s not in STAGE_ORDER]

def device_page_url(code):
    """Site-relative URL of a model's device page ('mt3000/'), or None if the
    model code would collide with a reserved root directory."""
    slug = code.lower()
    if slug in RESERVED_ROOT_NAMES:
        return None
    return f"{slug}/"



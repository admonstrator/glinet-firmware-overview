def parse_generated_at(generated_at):
    """'2026-09-26 13:23:07 UTC' -> naive datetime; falls back to now() for anything else."""
    try:
        return datetime.strptime((generated_at or '').replace(' UTC', '').strip(), '%Y-%m-%d %H:%M:%S')
    except ValueError:
        return datetime.now()

def build_date(entry):
    """Release date of a firmware entry as a date, or None when the API gave none."""
    try:
        return datetime.strptime((entry.get('release_time') or '')[:10], '%Y-%m-%d').date()
    except ValueError:
        return None

def days_since(entry, now):
    """Whole days between the entry's release date and `now` (a datetime), or None."""
    d = build_date(entry)
    return None if d is None else max(0, (now.date() - d).days)

def age_text(days):
    """Relative age for prose: 'today', 'yesterday', '5 days ago', '3 weeks ago', '4 months ago', '2 years ago'."""
    if days is None:
        return 'unknown'
    if days == 0:
        return 'today'
    if days == 1:
        return 'yesterday'
    if days < 14:
        return f'{days} days ago'
    if days < 60:
        return f'{days // 7} weeks ago'
    if days < 730:
        return f'{days // 30} months ago'
    return f'{days // 365} years ago'

def age_short(days):
    """Compact relative age for tables: '0d', '5d', '3w', '4mo', '2y' ('-' when unknown)."""
    if days is None:
        return '-'
    if days < 14:
        return f'{days}d'
    if days < 60:
        return f'{days // 7}w'
    if days < 730:
        return f'{days // 30}mo'
    return f'{days // 365}y'

def is_fresh(entry, now):
    """True when the build is at most FRESH_DAYS old."""
    d = days_since(entry, now)
    return d is not None and d <= FRESH_DAYS

def latest_update(stages):
    """(stage, entry) of the newest build across all stages of one device, or (None, None)."""
    best = (None, None)
    for stage, entry in stages.items():
        if best[1] is None or (entry.get('release_time') or '') > (best[1].get('release_time') or ''):
            best = (stage, entry)
    return best

def builds_newest_first(models, models_metadata, exclude=frozenset()):
    """Every build as a dict {code, name, type, stage, entry}, newest first (ties by code, stage)."""
    items = []
    for code, stages in models.items():
        meta = models_metadata.get(code, {})
        for stage, entry in stages.items():
            if stage in exclude:
                continue
            items.append({'code': code, 'name': meta.get('name', code), 'type': meta.get('type', 'ROUTER'),
                          'stage': stage, 'entry': entry})
    items.sort(key=lambda b: (b['code'].lower(), b['stage']))
    items.sort(key=lambda b: b['entry'].get('release_time') or '', reverse=True)
    return items

def recent_builds(models, models_metadata, now, days=RECENT_DAYS, exclude=RECENT_EXCLUDED_STAGES):
    """Builds released within `days` of `now`, newest first; each dict also carries 'days'.
    This is the single definition behind the overview section, /new and the global feed window."""
    out = []
    for b in builds_newest_first(models, models_metadata, exclude):
        d = days_since(b['entry'], now)
        if d is not None and d <= days:
            out.append(dict(b, days=d))
    return out

def feed_url(code=None, absolute=False, root=''):
    """URL of the global feed (code=None) or a device feed. Relative to the site root
    (prefix `root`, e.g. '../') unless absolute=True."""
    path = FEED_FILE if code is None else f'{code.lower()}/{FEED_FILE}'
    return f'{SITE_URL}/{path}' if absolute else f'{root}{path}'

def feed_entry_id(code, stage, version):
    """Stable Atom entry id for one build."""
    return f'tag:firmware.gl-i.net,2026:{code.lower()}/{api_stage_name(stage)}/{version}'

def split_name(name, code):
    """Split 'GL-MT3000 Beryl AX' into ('Beryl AX', 'GL-MT3000'). Names without a nickname stay
    whole; the second part then is the API code, or '' when the name already contains it."""
    parts = (name or code).split(' ', 1)
    if len(parts) == 2 and parts[0].upper().startswith(('GL-', 'MICROUTER')) and not parts[1].startswith('('):
        return parts[1], parts[0]
    full = name or code
    return full, ('' if code.upper() in full.upper() else code.upper())

def stage_class(stage):
    """CSS colour class of a stage: release, beta, snapshot, rc or other (clean, legacy, tor, ...).
    OpenWrt open variants (BETA_OPENxx) are beta."""
    s = stage.upper()
    if s.startswith('BETA_OPEN'):
        return 'beta'
    return s.lower() if s in ('RELEASE', 'BETA', 'SNAPSHOT', 'RC') else 'other'

def stage_title(stage, entry=None):
    """Human stage name for the new design: 'Release', 'Beta', 'Beta OP24', 'Clean', ..."""
    s = stage.upper()
    if s.startswith('BETA_OPEN'):
        base = (entry or {}).get('_openwrt_base') or s[len('BETA_OPEN'):] or '24'
        return f'Beta OP{base}'
    return s.capitalize()
